import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { format } from "prettier";
import { localeCodes } from "../app/i18n/locales";
import type { LessonPackage } from "../app/lesson/package";
import { validatePackage, validateManuscript, validateModelName } from "./validate-package";

export function readJson(path: string): unknown {
  if (statSync(path).size > 4 * 1024 * 1024)
    throw Error(path + " exceeds the 4 MiB authoring limit");
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    throw Error(path + ": " + String(error), { cause: error });
  }
}

export function discoverPackages(root: string) {
  const dir = join(root, "models");
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map(({ name }) => {
      const path = join(dir, name, "lesson.json");
      return validatePackage(readJson(path), name);
    })
    .sort((a, b) => a.order - b.order || (a.pattern.lessonId < b.pattern.lessonId ? -1 : 1));
}
export function publicEntries(packages: readonly LessonPackage[]) {
  return packages
    .filter((p) => p.status === "published")
    .map((p) => ({
      id: p.pattern.lessonId,
      availability: "playable" as const,
      stepCount: p.pattern.steps.length,
      paper: p.paper.shape,
      category: p.category,
      difficulty: p.difficulty,
      finishedAppearance: p.finishedAppearance,
    }));
}
export async function checkCatalog(root: string, write = false) {
  const packages = discoverPackages(root),
    entries = publicEntries(packages);
  for (const locale of localeCodes) {
    const dir = join(root, "app", "i18n", locale);
    const common = readJson(join(dir, "common.json")) as { models?: Record<string, unknown> };
    for (const p of packages) {
      if (p.status === "draft") continue;
      const id = p.manuscript;
      validateModelName(common?.models?.[id], locale + "/" + id);
      validateManuscript(readJson(join(dir, id + ".json")), p, locale);
    }
    for (const id of Object.keys(common.models ?? {}))
      if (!entries.some((e) => e.id === id))
        throw Error(locale + "/common.json: unlisted model " + id);
  }
  const banner = "// Generated by npm run models -- generate.\n";
  const outputs = {
    "app/model-index.generated.ts":
      banner + "export const lessons = " + JSON.stringify(entries) + " as const;\n",
    "app/lesson/package-loaders.generated.ts":
      banner +
      "export const packageLoaders = {\n" +
      entries
        .map(
          ({ id }) =>
            JSON.stringify(id) +
            ": () => import(" +
            JSON.stringify("../../models/" + id + "/lesson.json") +
            "),",
        )
        .join("\n") +
      "\n};\n",
  };
  for (const [file, source] of Object.entries(outputs)) {
    const result = await format(source, { parser: "typescript", printWidth: 100 });
    const path = join(root, file);
    if (write) writeFileSync(path, result);
    else if (readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== result)
      throw Error(file + " is stale. Run npm run models -- generate.");
  }
  return {
    packages: packages.length,
    published: entries.length,
    manuscripts: entries.length * localeCodes.length,
  };
}
